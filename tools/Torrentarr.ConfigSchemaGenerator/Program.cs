using System.Text.Json;
using Torrentarr.Core.Configuration;

var root = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../../"));
var outputPath = Path.Combine(root, "webui/src/config/configFields.generated.ts");
var json = JsonSerializer.Serialize(ConfigSchemaBuilder.Build(), new JsonSerializerOptions
{
    WriteIndented = true,
    NewLine = "\n"
});
var output = "// Generated by Torrentarr.ConfigSchemaGenerator. Do not edit.\n"
    + $"export const CONFIG_SCHEMA = {json} as const;\n\n"
    + "export type GeneratedConfigSchema = typeof CONFIG_SCHEMA;\n"
    + "export const CONFIG_SCHEMA_FIELD_COUNT = Object.values(CONFIG_SCHEMA.sections)\n"
    + "  .reduce((total, fields) => total + fields.length, 0);\n";

var docsPath = Path.Combine(root, "docs/configuration/maintenance-controls.md");
var docs = new System.Text.StringBuilder("# Manage control reference\n\nGenerated by `Torrentarr.ConfigSchemaGenerator`. All maintenance controls are available in Manage. Optional tools stay disabled until configured. Advanced settings preserve custom policies and limits.\n\n| Key | Kind | Default | Meaning |\n| --- | --- | --- | --- |\n");
foreach (var field in ConfigSchemaBuilder.Sections["TorrentClient"].Where(f => f.key.StartsWith("Maintenance.", StringComparison.Ordinal)))
{
    docs.AppendLine($"| `{field.key}` | {field.kind} | `{JsonSerializer.Serialize(field.@default)}` | {field.description?.Replace("|", "\\|")} |");
    foreach (var item in field.itemFields ?? [])
        docs.AppendLine($"| `{field.key}[].{item.key}` | {item.kind} | `{JsonSerializer.Serialize(item.@default)}` | {item.description?.Replace("|", "\\|")} |");
}
foreach (var field in ConfigSchemaBuilder.Sections["TrackerProtection"])
    docs.AppendLine($"| `Trackers[].Protection.{field.key}` | {field.kind} | `{JsonSerializer.Serialize(field.@default)}` | {field.description?.Replace("|", "\\|")} |");
var docsOutput = docs.ToString().Replace("\r\n", "\n");

if (args.Contains("--check", StringComparer.Ordinal))
{
    if (!File.Exists(outputPath) || File.ReadAllText(outputPath).Replace("\r\n", "\n") != output)
    {
        Console.Error.WriteLine($"Generated config schema is stale: {outputPath}");
        return 1;
    }

    if (!File.Exists(docsPath) || File.ReadAllText(docsPath).Replace("\r\n", "\n") != docsOutput)
    {
        Console.Error.WriteLine("Generated maintenance control documentation is stale."); return 1;
    }
    Console.WriteLine("Generated config schema and maintenance documentation are current.");
    return 0;
}

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, output);
File.WriteAllText(docsPath, docsOutput);
Console.WriteLine($"Generated {outputPath}");
return 0;
